export function getBroadcastCaseSummary(): string {
  const decisionCounts: Record<string, number> = {};
  const regulationCounts: Record<string, number> = {};

  for (const c of BUILTIN_BROADCAST_CASES) {
    decisionCounts[c.decision] = (decisionCounts[c.decision] || 0) + 1;
    const regKey = c.regulation.match(/제\d+조[^\s,]*/)?.[0] || c.regulation;
    regulationCounts[regKey] = (regulationCounts[regKey] || 0) + 1;
  }

  const lines = [
    "\n\n=== 방송심의 의결 사례 DB (2024년 상품판매방송 부문) ===",
    `총 ${BUILTIN_BROADCAST_CASES.length}건의 실제 심의 사례`,
    "",
    "【의결 유형별 현황】",
    ...Object.entries(decisionCounts).map(([k, v]) => `- ${k}: ${v}건`),
    "",
    "【주요 위반 규정】",
    ...Object.entries(regulationCounts)
      .sort((a, b) => b[1] - a[1])
      .slice(0, 10)
      .map(([k, v]) => `- ${k}: ${v}건`),
    "",
    "【주요 위반 유형 분류】",
    "- 화장품 효능·성분 과장: 제5조 제3항 위반 (권고~의견진술)",
    "- 미용기기→의료기기 오인: 제5조 제3항 위반 (권고~의견진술)",
    "- 건강기능식품 질병 예방·치료 오인: 제48조 제1항 제1호 위반 (의견진술)",
    "- 여행상품 조건 오인: 제5조 제2~3항 위반 (주의~의견진술)",
    "- 한정판매 허위 고지: 제15조 제2항 위반 (권고)",
    "- 수상·인증 과장: 제19조 제3항 위반 (주의)",
    "",
    "【최근 심의 사례 (상위 10건)】",
    ...BUILTIN_BROADCAST_CASES.slice(0, 10).map(
      (c, i) =>
        `${i + 1}. [${c.decision}] ${c.program}${c.broadcast_date ? ` (${c.broadcast_date})` : ""}\n   위반: ${c.violation.substring(0, 80)}...\n   규정: ${c.regulation}`
    ),
  ];

  return lines.join("\n");
}
